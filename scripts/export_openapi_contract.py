#!/usr/bin/env python3
"""
Enterprise OpenAPI 3.1 Contract & TypeScript Schema Generator / Drift Checker
=============================================================================
Exports FastAPI's deterministic OpenAPI schema to `contracts/openapi.json` and
generates strongly typed TypeScript interfaces in `src/api/schema.d.ts` so backend
API changes never silently break frontend consumers.

Usage:
    python scripts/export_openapi_contract.py          # Generate / update artifacts
    python scripts/export_openapi_contract.py --check  # Fail non-zero on drift (CI gate)
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

OPENAPI_OUT = ROOT / "contracts" / "openapi.json"
TS_SCHEMA_OUT = ROOT / "src" / "api" / "schema.d.ts"


def _sanitize_ts_identifier(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if cleaned and cleaned[0].isdigit():
        cleaned = f"_{cleaned}"
    return cleaned or "UnnamedSchema"


def _schema_to_ts(schema: Any, indent: int = 2) -> str:
    if not isinstance(schema, dict):
        return "unknown"

    if "$ref" in schema:
        ref_name = str(schema["$ref"]).rsplit("/", 1)[-1]
        return f"Schemas['{_sanitize_ts_identifier(ref_name)}']"

    if "anyOf" in schema:
        parts = [_schema_to_ts(s, indent) for s in schema["anyOf"]]
        deduped = list(dict.fromkeys(parts))
        return " | ".join(deduped) if deduped else "unknown"

    if "oneOf" in schema:
        parts = [_schema_to_ts(s, indent) for s in schema["oneOf"]]
        deduped = list(dict.fromkeys(parts))
        return " | ".join(deduped) if deduped else "unknown"

    if "allOf" in schema:
        parts = [_schema_to_ts(s, indent) for s in schema["allOf"]]
        return " & ".join(parts) if parts else "unknown"

    if "enum" in schema and isinstance(schema["enum"], list):
        literals = [json.dumps(v) for v in schema["enum"]]
        return " | ".join(literals) if literals else "unknown"

    if "const" in schema:
        return json.dumps(schema["const"])

    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(dict.fromkeys(_schema_to_ts({**schema, "type": item}, indent) for item in t))

    if t == "null":
        return "null"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "string":
        return "string"
    if t == "array":
        item_ts = _schema_to_ts(schema.get("items", {}), indent)
        if " | " in item_ts or " & " in item_ts:
            return f"Array<({item_ts})>"
        return f"{item_ts}[]"
    if t == "object" or "properties" in schema:
        props = schema.get("properties") or {}
        if not props:
            addl = schema.get("additionalProperties")
            if isinstance(addl, dict):
                return f"Record<string, {_schema_to_ts(addl, indent)}>"
            return "Record<string, unknown>"
        required = set(schema.get("required") or [])
        pad = " " * (indent + 2)
        end_pad = " " * indent
        lines = ["{"]
        for prop_name in sorted(props.keys()):
            prop_schema = props[prop_name]
            opt = "" if prop_name in required else "?"
            safe_key = prop_name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", prop_name) else json.dumps(prop_name)
            lines.append(f"{pad}{safe_key}{opt}: {_schema_to_ts(prop_schema, indent + 2)};")
        lines.append(f"{end_pad}}}")
        return "\n".join(lines)

    return "unknown"


def render_typescript_definitions(spec: Dict[str, Any]) -> str:
    schemas = (spec.get("components") or {}).get("schemas") or {}
    paths = spec.get("paths") or {}

    lines: List[str] = [
        "/*",
        " * AUTO-GENERATED BY scripts/export_openapi_contract.py — DO NOT EDIT MANUALLY.",
        " * Run `python scripts/export_openapi_contract.py` after modifying FastAPI schemas.",
        " */",
        "",
        "export interface ApiErrorEnvelope {",
        "  detail: string;",
        "  correlation_id?: string;",
        "  errors?: Array<{ loc?: Array<string | number>; msg?: string; type?: string }>;",
        "}",
        "",
        "export interface Schemas {",
    ]

    for raw_name in sorted(schemas.keys()):
        ts_name = _sanitize_ts_identifier(raw_name)
        ts_type = _schema_to_ts(schemas[raw_name], indent=2)
        lines.append(f"  {ts_name}: {ts_type};")

    lines.append("}")
    lines.append("")
    lines.append("export type ApiEndpoints = {")
    for path in sorted(paths.keys()):
        methods = sorted(
            m.upper()
            for m in paths[path].keys()
            if m.lower() in {"get", "post", "put", "patch", "delete", "head", "options"}
        )
        if not methods:
            continue
        method_union = " | ".join(json.dumps(m) for m in methods)
        lines.append(f"  {json.dumps(path)}: {method_union};")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def build_contracts() -> tuple[str, str]:
    os.environ.setdefault("OUTBOUND_EGRESS_ENABLED", "false")
    from main import app

    spec = app.openapi()
    openapi_text = json.dumps(spec, sort_keys=True, indent=2, ensure_ascii=False) + "\n"
    ts_text = render_typescript_definitions(spec)
    return openapi_text, ts_text


def main() -> int:
    parser = argparse.ArgumentParser(description="Export or verify OpenAPI and TypeScript API contracts.")
    parser.add_argument("--check", action="store_true", help="Fail non-zero if committed contracts drift from live app.")
    args = parser.parse_args()

    openapi_text, ts_text = build_contracts()

    if args.check:
        drifts = []
        if not OPENAPI_OUT.exists() or OPENAPI_OUT.read_text(encoding="utf-8") != openapi_text:
            drifts.append(str(OPENAPI_OUT.relative_to(ROOT)))
        if not TS_SCHEMA_OUT.exists() or TS_SCHEMA_OUT.read_text(encoding="utf-8") != ts_text:
            drifts.append(str(TS_SCHEMA_OUT.relative_to(ROOT)))
        if drifts:
            print(
                "ERROR: API contract drift detected in: " + ", ".join(drifts) + "\n"
                "Run `python scripts/export_openapi_contract.py` to refresh contracts.",
                file=sys.stderr,
            )
            return 1
        print("OK: OpenAPI JSON and TypeScript API contracts are in sync.")
        return 0

    OPENAPI_OUT.parent.mkdir(parents=True, exist_ok=True)
    TS_SCHEMA_OUT.parent.mkdir(parents=True, exist_ok=True)
    OPENAPI_OUT.write_text(openapi_text, encoding="utf-8")
    TS_SCHEMA_OUT.write_text(ts_text, encoding="utf-8")
    print(f"Exported {OPENAPI_OUT.relative_to(ROOT)} and {TS_SCHEMA_OUT.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
